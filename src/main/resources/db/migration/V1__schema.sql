CREATE TABLE users (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 name VARCHAR(100) NOT NULL, email VARCHAR(180) NOT NULL UNIQUE,
 password_hash VARCHAR(100) NOT NULL, role VARCHAR(20) NOT NULL CHECK(role IN ('CLIENTE','TRABAJADOR','ADMIN')),
 phone VARCHAR(30) NOT NULL, city VARCHAR(80) NOT NULL,
 bio VARCHAR(1200) NOT NULL DEFAULT '', experience INTEGER NOT NULL DEFAULT 0,
 available BOOLEAN NOT NULL DEFAULT TRUE, radius_km INTEGER NOT NULL DEFAULT 15,
 latitude DOUBLE PRECISION, longitude DOUBLE PRECISION,
 active BOOLEAN NOT NULL DEFAULT TRUE, avatar_id VARCHAR(40),
 created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE user_skills (
 user_id BIGINT NOT NULL REFERENCES users(id), category_id BIGINT NOT NULL REFERENCES categories(id),
 PRIMARY KEY(user_id,category_id)
);
CREATE TABLE auth_sessions (
 token_hash VARCHAR(64) PRIMARY KEY, user_id BIGINT NOT NULL REFERENCES users(id),
 expires_at TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE INDEX idx_sessions_user ON auth_sessions(user_id);
CREATE TABLE password_resets (
 token_hash VARCHAR(64) PRIMARY KEY, user_id BIGINT NOT NULL REFERENCES users(id),
 expires_at TIMESTAMP WITH TIME ZONE NOT NULL, used BOOLEAN NOT NULL DEFAULT FALSE
);
CREATE TABLE jobs (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 client_id BIGINT NOT NULL REFERENCES users(id), category_id BIGINT NOT NULL REFERENCES categories(id),
 title VARCHAR(150) NOT NULL, description VARCHAR(4000) NOT NULL,
 city VARCHAR(80) NOT NULL, zone VARCHAR(120) NOT NULL, address VARCHAR(240) NOT NULL,
 latitude DOUBLE PRECISION, longitude DOUBLE PRECISION,
 scheduled_at TIMESTAMP WITH TIME ZONE NOT NULL, duration_hours INTEGER NOT NULL CHECK(duration_hours BETWEEN 1 AND 24),
 workers_needed INTEGER NOT NULL CHECK(workers_needed BETWEEN 1 AND 10),
 initial_price BIGINT NOT NULL CHECK(initial_price > 0), current_price BIGINT NOT NULL CHECK(current_price > 0),
 max_price BIGINT NOT NULL CHECK(max_price >= current_price), increment_amount BIGINT NOT NULL CHECK(increment_amount > 0),
 interval_minutes INTEGER NOT NULL CHECK(interval_minutes > 0), auto_increase BOOLEAN NOT NULL DEFAULT FALSE,
 next_increase_at TIMESTAMP WITH TIME ZONE,
 status VARCHAR(40) NOT NULL DEFAULT 'PUBLICADO', hidden BOOLEAN NOT NULL DEFAULT FALSE,
 cancel_reason VARCHAR(1000), created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX idx_jobs_status ON jobs(status,scheduled_at);
CREATE INDEX idx_jobs_client ON jobs(client_id);
CREATE TABLE price_history (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, job_id BIGINT NOT NULL REFERENCES jobs(id),
 amount BIGINT NOT NULL, origin VARCHAR(30) NOT NULL,
 created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE assignments (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 job_id BIGINT NOT NULL REFERENCES jobs(id), worker_id BIGINT NOT NULL REFERENCES users(id),
 agreed_price BIGINT NOT NULL CHECK(agreed_price > 0), status VARCHAR(40) NOT NULL DEFAULT 'ACEPTADO',
 accepted_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
 completed_at TIMESTAMP WITH TIME ZONE, UNIQUE(job_id,worker_id)
);
CREATE INDEX idx_assignments_worker ON assignments(worker_id);
CREATE TABLE job_events (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, job_id BIGINT NOT NULL REFERENCES jobs(id),
 assignment_id BIGINT REFERENCES assignments(id), actor_id BIGINT REFERENCES users(id),
 kind VARCHAR(60) NOT NULL, detail VARCHAR(1000) NOT NULL,
 created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE media (
 id VARCHAR(40) PRIMARY KEY, owner_id BIGINT NOT NULL REFERENCES users(id),
 job_id BIGINT REFERENCES jobs(id), assignment_id BIGINT REFERENCES assignments(id),
 object_path VARCHAR(300) NOT NULL, provider VARCHAR(20) NOT NULL,
 content_type VARCHAR(60) NOT NULL, size_bytes BIGINT NOT NULL,
 created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE messages (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, assignment_id BIGINT NOT NULL REFERENCES assignments(id),
 sender_id BIGINT NOT NULL REFERENCES users(id), body VARCHAR(2000) NOT NULL,
 media_id VARCHAR(40) REFERENCES media(id), read_at TIMESTAMP WITH TIME ZONE,
 created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX idx_messages_assignment ON messages(assignment_id,id);
CREATE TABLE reviews (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 assignment_id BIGINT NOT NULL REFERENCES assignments(id), author_id BIGINT NOT NULL REFERENCES users(id),
 target_id BIGINT NOT NULL REFERENCES users(id), score INTEGER NOT NULL CHECK(score BETWEEN 1 AND 5),
 comment VARCHAR(1500) NOT NULL,
 created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
 UNIQUE(assignment_id,author_id)
);
CREATE TABLE domain_events (
 id VARCHAR(40) PRIMARY KEY, kind VARCHAR(60) NOT NULL,
 actor_id BIGINT REFERENCES users(id), job_id BIGINT REFERENCES jobs(id),
 title VARCHAR(200) NOT NULL, detail VARCHAR(1000) NOT NULL,
 created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE notifications (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, event_id VARCHAR(40) NOT NULL REFERENCES domain_events(id),
 user_id BIGINT NOT NULL REFERENCES users(id), job_id BIGINT REFERENCES jobs(id),
 title VARCHAR(200) NOT NULL, body VARCHAR(1000) NOT NULL, is_read BOOLEAN NOT NULL DEFAULT FALSE,
 created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
 UNIQUE(event_id,user_id)
);
CREATE INDEX idx_notifications_user ON notifications(user_id,is_read);
CREATE TABLE reports (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, author_id BIGINT NOT NULL REFERENCES users(id),
 job_id BIGINT NOT NULL REFERENCES jobs(id), reason VARCHAR(60) NOT NULL, detail VARCHAR(2500) NOT NULL,
 status VARCHAR(30) NOT NULL DEFAULT 'ABIERTO', resolution VARCHAR(2500),
 resolved_by BIGINT REFERENCES users(id), created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
 updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);
